export type IconName = keyof typeof PATHS;

export function Icon({ name, size = 18, ...rest }: { name: IconName; size?: number } & SVGProps<SVGSVGElement>) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2}
      strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" {...rest}>
      {PATHS[name]}
    </svg>
  );
}

/** The Inkventory mark: a storefront on the brand gradient (the same file as the favicon, so they never drift). */
export function LogoMark({ size = 32 }: { size?: number }) {
  // Gradient/filter ids are made unique so several marks on one page don't share definitions.
  const id = useId().replace(/[^a-zA-Z0-9]/g, "");
  const svg = markSvg.replace(/vJ/g, `m${id}`).replace("<svg ", `<svg width="${size}" height="${size}" aria-hidden="true" `);
  return <span className="logo-mark" style={{ width: size, height: size }} dangerouslySetInnerHTML={{ __html: svg }} />;
}

/** Logo lockup: mark + "Inkventory" wordmark with "Ink" in the accent color. */
export function Logo({ size = 32, dark = false }: { size?: number; dark?: boolean }) {
  return (
    <span className={`logo ${dark ? "dark" : ""}`}>
      <LogoMark size={size} />
      <span className="logo-word"><span>Ink</span>ventory</span>
    </span>
  );
}
